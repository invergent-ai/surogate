def patch(text: str, old: str, new: str, count: int = 1, replace: int | None = None) -> str:
    n = text.count(old)
    if n != count:
        raise SystemExit(f"make_fork: anchor found {n}x (want {count}): {old[:90]!r}")
    return text.replace(old, new, count if replace is None else replace)


def patch_span(text: str, start: str, end: str, new: str) -> str:
    """Replace from the FIRST occurrence of `start` through the first `end` after it."""
    i = text.find(start)
    if i < 0:
        raise SystemExit(f"make_fork: span start not found: {start[:90]!r}")
    j = text.find(end, i)
    if j < 0:
        raise SystemExit(f"make_fork: span end not found: {end[:90]!r}")
    return text[:i] + new + text[j + len(end):]


