#!/usr/bin/env python3
"""Generate the weight-only NVFP4 (W4A16) Marlin instantiations surogate serve needs.

vLLM serves ModelOpt's W4A16_NVFP4 checkpoints through Marlin on every GPU without FP4
activations (MarlinNvFp4LinearKernel for the dense layers, the MARLIN NVFP4 MoE backend for
the experts), and the vendored dense and MoE templates already carry that path: kFE2M1f codes,
kFE4M3fn scales at group 16 (group_blocks 1), an FP32 global scale. This emits only that
corner -- bf16 activations and output -- for both templates, and the selector arms that reach
them. The thread configurations are the ones each dispatcher tries: (128, 128, 256),
(64, 128, 128) and (128, 64, 128) for one 16-row block (and its 8-row variant), (64, 256, 256),
(64, 128, 128) and (128, 64, 128) above it.

Run from the repo root:
    python3 csrc/src/serve/ops/linear/marlin/generate_nvfp4_kernels.py
"""

from __future__ import annotations

import pathlib

HERE = pathlib.Path(__file__).resolve().parent
MOE = HERE.parents[1] / "sparse_moe" / "marlin"

A_TYPE = "vllm::kBFloat16"
B_TYPE = "vllm::kFE2M1f"
C_TYPE = "vllm::kBFloat16"
S_TYPE = "vllm::kFE4M3fn"
GROUP_BLOCKS = 1  # NVFP4: one E4M3 scale per 16 values
STAGES = 4

SMALL = [(128, 128, 256), (64, 128, 128), (128, 64, 128)]  # thread_k, thread_n, threads
LARGE = [(64, 256, 256), (64, 128, 128), (128, 64, 128)]


def configurations():
    """(threads, thread_m_blocks, thread_n_blocks, thread_k_blocks, m_block_size_8)."""
    for m8 in (True, False):
        for thread_k, thread_n, threads in SMALL:
            yield threads, 1, thread_n // 16, thread_k // 16, m8
    for m in (2, 3, 4):
        for thread_k, thread_n, threads in LARGE:
            yield threads, m, thread_n // 16, thread_k // 16, False


def template(config) -> str:
    threads, m, n, k, m8 = config
    return (f"Marlin<{A_TYPE}.id(), {B_TYPE}.id(), {C_TYPE}.id(), {S_TYPE}.id(), {threads}, {m}, "
            f"{n}, {k}, {'true' if m8 else 'false'}, {STAGES}, {GROUP_BLOCKS}, false>")


def selector() -> str:
    lines = ["// Generated by generate_nvfp4_kernels.py: the weight-only NVFP4 arms. Do not edit.",
             "// clang-format off"]
    for index, config in enumerate(configurations()):
        threads, m, n, k, m8 = config
        keyword = "if" if index == 0 else "else if"
        lines.append(
            f"{keyword} (a_type == {A_TYPE} && b_type == {B_TYPE} && c_type == {C_TYPE} && "
            f"s_type == {S_TYPE} && threads == {threads} && thread_m_blocks == {m} && "
            f"thread_n_blocks == {n} && thread_k_blocks == {k} && "
            f"m_block_size_8 == {'true' if m8 else 'false'} && stages == {STAGES} && "
            f"group_blocks == {GROUP_BLOCKS} && is_zp_float == false)")
        lines.append(f"  kernel = {template(config)};")
    return "\n".join(lines) + "\n"


def kernels(include_kernel: str, include_template: str) -> str:
    body = "\n".join(f"template __global__ void {template(config)}( MARLIN_KERNEL_PARAMS );\n"
                     for config in configurations())
    return ("// Generated by generate_nvfp4_kernels.py from the vendored vLLM Marlin template\n"
            "// (Apache-2.0): the weight-only NVFP4 instantiations. Do not edit by hand.\n"
            "// clang-format off\n\n"
            f'#include "{include_kernel}"\n#include "{include_template}"\n\n'
            "namespace MARLIN_NAMESPACE_NAME {\n\n" + body + "\n} // namespace MARLIN_NAMESPACE_NAME\n")


def main() -> None:
    (HERE / "marlin_nvfp4_kernels_generated.cu").write_text(
        kernels("ops/linear/marlin/vendor/kernel.h", "ops/linear/marlin/vendor/marlin_template.h"))
    (HERE / "kernel_selector_nvfp4_generated.h").write_text(selector())
    (MOE / "marlin_moe_nvfp4_kernels_generated.cu").write_text(
        kernels("ops/sparse_moe/marlin/vendor/kernel.h",
                "ops/sparse_moe/marlin/vendor/marlin_moe_template.h"))
    (MOE / "marlin_moe_nvfp4_selector_generated.h").write_text(selector())


if __name__ == "__main__":
    main()
