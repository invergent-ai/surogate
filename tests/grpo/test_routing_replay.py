    assert moe_layer_ids({"num_hidden_layers": 4}, get) == [0, 1, 2, 3]
    assert moe_layer_ids({"num_hidden_layers": 6, "decoder_sparse_step": 2, "mlp_only_layers": [3]}, get) == [1, 5]
    assert moe_layer_ids({"num_hidden_layers": 4, "first_k_dense_replace": 1}, get) == [1, 2, 3]


