"""Extract the serving engine's n-gram row selection VERBATIM (csrc/src/serve/api/ops/ngram_ple.h: the limits and
NgramPleHash; csrc/src/serve/ops/ngram_ple/ngram_ple.cu: predecessor() and rows_kernel) into a self-contained header
for ngram_rows_parity.cu, so the parity test runs the engine's own kernel text without the engine's framework.

    python extract_engine_rows.py REPO_ROOT OUT_HEADER
"""
import re
import sys
from pathlib import Path


def block(text, start_pat):
    """The text from the first match of start_pat through its matching closing brace (and a trailing ';')."""
    m = re.search(start_pat, text, re.M)
    if not m:
        raise SystemExit(f"not found: {start_pat}")
    i = text.index("{", m.end() - 1 if text[m.end() - 1] == "{" else m.end())
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                end = j + 1
                if end < len(text) and text[end] == ";":
                    end += 1
                return text[m.start():end]
    raise SystemExit("unbalanced braces")


root = Path(sys.argv[1])
h = (root / "csrc/src/serve/api/ops/ngram_ple.h").read_text()
cu = (root / "csrc/src/serve/ops/ngram_ple/ngram_ple.cu").read_text()
limits = "\n".join(re.findall(r"^inline constexpr std::int32_t kNgramPleMax\w+ = \d+;$", h, re.M))
struct = block(h, r"^struct NgramPleHash \{")
pred = block(cu, r"^__device__ __forceinline__ int predecessor\(")
rows = block(cu, r"^__global__ void rows_kernel\(")
out = f"""// GENERATED by extract_engine_rows.py from the serving engine sources (verbatim). Do not edit.
#pragma once
#include <cstdint>
#include <cuda_runtime.h>
namespace engine_rows {{
{limits}
{struct}
namespace {{
{pred}

{rows}
}}  // namespace
}}  // namespace engine_rows
"""
Path(sys.argv[2]).write_text(out)
print(f"extracted {len(out)} bytes")
